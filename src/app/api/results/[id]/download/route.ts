import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import PDFDocument from "pdfkit";

export async function GET(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const { id } = await params;
    const result = await prisma.analysisResult.findUnique({
      where: { id },
      include: { video: true },
    });

    if (!result || result.status !== "completed" || result.prediction == null) {
      return NextResponse.json({ error: "Result not available" }, { status: 404 });
    }

    const isDf = result.prediction >= 0.5;
    const score = (result.prediction * 100).toFixed(1);
    const confidence = result.confidence != null ? (result.confidence * 100).toFixed(0) : "N/A";

    const doc = new PDFDocument({ size: "A4", margins: { top: 50, bottom: 50, left: 50, right: 50 } });
    const buffers: Buffer[] = [];
    doc.on("data", (chunk: Buffer) => buffers.push(chunk));

    doc.fontSize(24).font("Helvetica-Bold").text("VeriSight", { align: "center" });
    doc.fontSize(10).font("Helvetica").fillColor("#666")
      .text("Deepfake Detection Report", { align: "center" }).moveDown(2);

    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor("#ccc").stroke().moveDown(1);

    doc.fontSize(16).font("Helvetica-Bold").fillColor("#000")
      .text("Detection Verdict", { align: "center" }).moveDown(0.5);
    doc.fontSize(28).font("Helvetica-Bold")
      .fillColor(isDf ? "#ef4444" : "#10b981")
      .text(isDf ? "DEEPFAKE DETECTED" : "AUTHENTIC", { align: "center" }).moveDown(1.5);

    const riskColor: Record<string, string> = { critical: "#ef4444", high: "#f59e0b", medium: "#3b82f6", low: "#10b981" };
    doc.fontSize(12).font("Helvetica").fillColor(riskColor[result.riskLevel ?? "low"] ?? "#666")
      .text("Risk Level: " + (result.riskLevel ?? "UNKNOWN").toUpperCase(), { align: "center" }).moveDown(2);

    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor("#ccc").stroke().moveDown(1);
    doc.fontSize(14).font("Helvetica-Bold").fillColor("#000").text("Analysis Details").moveDown(0.5);

    const rows: [string, string][] = [
      ["Deepfake Score", score + "%"],
      ["Confidence", confidence + "%"],
      ["Verdict", isDf ? "Deepfake Detected" : "Likely Authentic"],
      ["Risk Level", (result.riskLevel ?? "unknown").toUpperCase()],
      ["Frames Analyzed", (result.framesAnalyzed ?? 0) + " / " + (result.totalFrames ?? 0)],
      ["Processing Time", result.processingTimeMs ? (result.processingTimeMs / 1000).toFixed(1) + "s" : "N/A"],
      ["Date Analyzed", new Date(result.createdAt).toLocaleString()],
    ];

    const tableTop = doc.y;
    for (let i = 0; i < rows.length; i++) {
      const y = tableTop + i * 22;
      doc.fontSize(10).font("Helvetica-Bold").fillColor("#333").text(rows[i][0], 50, y);
      doc.font("Helvetica").fillColor("#000").text(rows[i][1], 220, y);
    }

    doc.moveDown(2);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor("#ccc").stroke().moveDown(1);
    doc.fontSize(14).font("Helvetica-Bold").fillColor("#000").text("Recommendations").moveDown(0.5);
    doc.fontSize(10).font("Helvetica").fillColor("#333");

    const recs = isDf
      ? ["Do not share unverified content. Deepfakes can spread misinformation.",
         "Examine visual artifacts, unnatural blinking, and audio-visual desynchronization.",
         "Verify the source and cross-reference with trusted media."]
      : ["Content appears authentic with no significant deepfake indicators.",
         "Cross-verify the video source for contextual consistency.",
         "Stay vigilant as deepfake technology evolves rapidly."];
    for (const rec of recs) {
      doc.text("\u2022 " + rec);
    }

    doc.moveDown(3);
    doc.moveTo(50, doc.y).lineTo(545, doc.y).strokeColor("#ccc").stroke().moveDown(1);
    doc.fontSize(8).font("Helvetica").fillColor("#999")
      .text("Generated by VeriSight \u2014 AI-Powered Deepfake Detection", { align: "center" });

    doc.end();

    await new Promise<void>((resolve) => doc.on("end", resolve));

    const pdfBuffer = Buffer.concat(buffers);

    return new Response(pdfBuffer, {
      status: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="verisight-report-${result.id}.pdf"`,
        "Content-Length": pdfBuffer.length.toString(),
      },
    });
  } catch (e: unknown) {
    const msg = e instanceof Error ? e.message : "Failed to generate report";
    console.error("PDF generation error:", msg);
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}
